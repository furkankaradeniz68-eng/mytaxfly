export const config = {
  api: { bodyParser: { sizeLimit: '12mb' } }
};

export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const { advisorEmail, clientName, corpName, taxYear, pdfBase64 } = req.body || {};
  if (!advisorEmail || !pdfBase64) {
    return res.status(400).json({ error: 'Missing advisorEmail or pdfBase64' });
  }

  const RESEND_API_KEY = process.env.RESEND_API_KEY;
  if (!RESEND_API_KEY) {
    return res.status(500).json({ error: 'Email service not configured (RESEND_API_KEY missing)' });
  }

  const safeCorpName = (corpName || 'LLC').replace(/[^a-zA-Z0-9 _-]/g, '');
  const filename = `FilingPackage_${safeCorpName.replace(/\s+/g, '_')}_${taxYear || 'current'}.pdf`;

  const emailPayload = {
    from: 'MyTaxFly <noreply@mytaxfly.com>',
    to: [advisorEmail],
    subject: `IRS Filing Package — ${safeCorpName} — Tax Year ${taxYear || ''}`,
    html: `
      <div style="font-family:Arial,sans-serif;max-width:600px;margin:0 auto;padding:32px;color:#333">
        <div style="font-size:26px;font-weight:900;color:#00c896;margin-bottom:4px">MyTaxFly</div>
        <div style="font-size:18px;font-weight:700;margin-bottom:20px;color:#111">IRS Filing Package · Tax Year ${taxYear || ''}</div>
        <p>Your client <strong>${clientName || 'a MyTaxFly user'}</strong> has shared their annual IRS filing package with you.</p>
        <p>The attached PDF contains:</p>
        <ul>
          <li><strong>Pro Forma Form 1120</strong> — U.S. Corporation Income Tax Return</li>
          <li><strong>Form 5472</strong> — Information Return (25% Foreign-Owned U.S. LLC)</li>
        </ul>
        <div style="background:#fff8e1;border:1px solid #f6ad55;border-radius:8px;padding:16px;margin-top:24px;font-size:13px;color:#7a5700">
          ⚠ This is a pre-filled working draft generated by MyTaxFly. Please review all figures carefully and obtain client signature before filing with the IRS.
        </div>
        <div style="margin-top:32px;padding-top:20px;border-top:1px solid #eee;font-size:12px;color:#999">
          Sent via <a href="https://mytaxfly.com" style="color:#00c896;text-decoration:none">MyTaxFly</a> · mytaxfly.com
        </div>
      </div>
    `,
    attachments: [{ filename, content: pdfBase64 }]
  };

  try {
    const emailRes = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${RESEND_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify(emailPayload)
    });
    const data = await emailRes.json();
    if (!emailRes.ok) {
      return res.status(500).json({ error: data.message || 'Email send failed', detail: data });
    }
    return res.status(200).json({ ok: true, id: data.id });
  } catch (e) {
    return res.status(500).json({ error: e.message });
  }
}
